def palette() -> list[int]:
    colors = [
        (0, 0, 0),
        (245, 242, 228),
        (88, 92, 99),
        (190, 55, 45),
        (235, 164, 74),
        (80, 150, 105),
        (67, 128, 180),
        (130, 88, 170),
        (229, 218, 136),
        (38, 40, 48),
        (97, 62, 46),
        (136, 92, 52),
        (184, 126, 62),
        (78, 112, 88),
        (63, 112, 142),
        (246, 236, 184),
    ]
    out: list[int] = []
    for r, g, b in colors:
        out.extend((r, g, b))
    return out + [0] * ((256 * 3) - len(out))


def draw_glyph(img: Image.Image, code: int, char: str) -> None:
    rows = GLYPHS.get(char)
    if rows is None:
        return
    x0 = code * 8 + 1
    for y, row in enumerate(rows):
        for x, on in enumerate(row):
            if on == "1":
                img.putpixel((x0 + x, y), 1)


def make_fix(path: Path) -> None:
    img = Image.new("P", (256 * 8, 8), 0)
    img.putpalette(palette())
    for code in range(32, 127):
        draw_glyph(img, code, chr(code).upper())
    img.save(path)


def make_card(path: Path) -> None:
    img = Image.new("P", (16, 512), 0)
    img.putpalette(palette())
    for y in range(512):
        for x in range(16):
            if y == 511:
                idx = 0
            elif x in (0, 15) or y % 64 in (0, 1):
                idx = 15
            elif y % 32 in (14, 15):
                idx = 4 + ((y // 64) % 4)
            elif (x + (y // 8)) % 7 == 0:
                idx = 14
            elif x in (4, 8, 12):
                idx = 9 + ((y // 48 + x) % 5)
            else:
                idx = 1 + ((x * 3 + y // 16) % 13)
            img.putpixel((x, y), idx)
    img.save(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fix", type=Path, required=True)
    parser.add_argument("--card", type=Path, required=True)
    args = parser.parse_args()
    args.fix.parent.mkdir(parents=True, exist_ok=True)
    args.card.parent.mkdir(parents=True, exist_ok=True)
    make_fix(args.fix)
    make_card(args.card)


if __name__ == "__main__":
    main()
